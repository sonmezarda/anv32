#!/usr/bin/env python3
"""Core-only FPGA evaluation: Fmax and utilization per core and target.

Each core from sim/corebench/cores.json is synthesized, placed and routed
inside fpga/eval/core_eval_top.sv for each target in fpga/eval/targets.json
(Gowin or Vivado). A target can list implementation variants (placement
algorithms or directives); --variants all runs each of them and keeps the
best. Results go to build/fpga_eval/<target>/<core>/<variant>/ and the best
run per core and target is merged into build/fpga_eval/summary.json, which
tools/run_corebench.py reads with --fmax-json. See docs/corebench.md.

Windows tools are supported from WSL: give the path of gw_sh.exe or
vivado.bat and every path handed to the tool is converted with wslpath.
"""

from __future__ import annotations

import argparse
import concurrent.futures
import datetime
import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

CORES_JSON = "sim/corebench/cores.json"
TARGETS_JSON = "fpga/eval/targets.json"
EVAL_RTL = ["rtl/common/mem/anv32_bram_tdp.sv", "fpga/eval/core_eval_top.sv"]


def split_list(value: str) -> list[str]:
    return [item.strip() for item in value.split(",") if item.strip()]


def is_windows_tool(tool: str) -> bool:
    return tool.lower().endswith((".exe", ".bat"))


def tool_path(path: Path, windows: bool) -> str:
    """A path as the tool sees it; Tcl accepts forward slashes on Windows."""
    if not windows:
        return str(path)
    return subprocess.run(["wslpath", "-m", str(path)], text=True, capture_output=True,
                          check=True).stdout.strip()


def tcl_list(items: list[str]) -> str:
    return "[list " + " ".join("{" + item + "}" for item in items) + "]"


def target_variants(target: dict) -> dict[str, str]:
    """Variant name -> Tcl the flow evaluates before implementation."""
    return target.get("variants") or {"default": ""}


def write_build_tcl(repo: Path, core: str, spec: dict, target: dict, variant: str,
                    run_dir: Path, windows: bool) -> Path:
    files = [*spec["sources"], spec["adapter"], *EVAL_RTL]
    as_tool = lambda rel: tool_path((repo / rel).resolve(), windows)
    lines = [
        "# Generated by tools/fpga_eval.py",
        f"set eval_name        {core}",
        "set eval_top         core_eval_top",
        f"set eval_device      {target['device']}",
        f"set eval_device_name {target.get('device_name', target['device'])}",
        f"set eval_files       {tcl_list([as_tool(f) for f in files])}",
        f"set eval_incdirs     {tcl_list([as_tool(d) for d in spec.get('include_dirs', [])])}",
        f"set eval_constraints {tcl_list([as_tool(c) for c in target['constraints']])}",
        f"set eval_out         {{{tool_path(run_dir, windows)}}}",
        f"set eval_variant     {{{target_variants(target)[variant]}}}",
        f"source {{{as_tool('fpga/eval/' + target['tool'] + '_eval.tcl')}}}",
    ]
    build_tcl = run_dir / "build.tcl"
    build_tcl.write_text("\n".join(lines) + "\n")
    return build_tcl


def run_tool(args: argparse.Namespace, tool: str, run_dir: Path, build_tcl: Path) -> None:
    exe = args.gowin if tool == "gowin" else args.vivado
    windows = is_windows_tool(exe)
    script = tool_path(build_tcl, windows)
    if tool == "gowin":
        cmd = [exe, script]
    else:
        cmd = [exe, "-mode", "batch", "-nojournal",
               "-log", tool_path(run_dir / "vivado.log", windows), "-source", script]
    if exe.lower().endswith(".bat"):
        # cmd.exe cannot start in a WSL (UNC) directory; run from %TEMP%
        cmd[0] = subprocess.run(["wslpath", "-w", exe], text=True, capture_output=True,
                                check=True).stdout.strip()
        cmd = ["cmd.exe", "/c", "cd /d %TEMP% && " + subprocess.list2cmdline(cmd)]
    with (run_dir / "tool.log").open("w") as log:
        log.write("+ " + shlex.join(cmd) + "\n")
        log.flush()
        proc = subprocess.run(cmd, cwd=run_dir, stdout=log, stderr=subprocess.STDOUT)
    if proc.returncode != 0:
        raise RuntimeError(f"{tool} exited with {proc.returncode}, see {run_dir / 'tool.log'}")


# ---- Report parsing --------------------------------------------------------

def parse_gowin(run_dir: Path, core: str) -> dict:
    pnr = run_dir / "impl" / "pnr"
    rpt = (pnr / f"{core}.rpt.txt").read_text(errors="replace")
    timing = (pnr / f"{core}.tr").read_text(errors="replace")

    def usage(label: str) -> str:
        match = re.search(rf"^\s*{re.escape(label)}\s*\|\s*([^|]+?)\s*\|", rpt, re.M)
        return match.group(1) if match else ""

    def count(text: str) -> int:
        # Gowin leaves out the rows of resources the design does not use
        match = re.match(r"(\d+)", text)
        return int(match.group(1)) if match else 0

    fmax = re.search(r"^\s*\d+\s+clk_i\s+([\d.]+)\(MHz\)\s+([\d.]+)\(MHz\)\s+(\d+)", timing, re.M)
    return {
        "constraint_mhz": float(fmax.group(1)) if fmax else None,
        "fmax_mhz": float(fmax.group(2)) if fmax else None,
        "logic_levels": int(fmax.group(3)) if fmax else None,
        "lut": count(usage("Logic")),
        "lut_detail": usage("--LUT,ALU,ROM16"),
        "lutram": count(usage("--SSRAM(RAM16)")),
        "ff": count(usage("Register")),
        "bram": count(usage("BSRAM")),
        "dsp": count(usage("DSP")),
    }


def parse_vivado(run_dir: Path) -> dict:
    fmax = dict(line.split() for line in (run_dir / "fmax.txt").read_text().splitlines() if line.strip())
    util = (run_dir / "route_util.rpt").read_text(errors="replace")
    paths = (run_dir / "timing_paths.rpt").read_text(errors="replace")

    def used(label: str) -> float | None:
        match = re.search(rf"^\|\s*{re.escape(label)}\s*\|\s*([\d.]+)\s*\|", util, re.M)
        return float(match.group(1)) if match else None

    def as_int(value: float | None) -> int | float | None:
        return int(value) if value is not None and value.is_integer() else value

    levels = re.search(r"Logic Levels:\s+(\d+)", paths)
    lut = used("Slice LUTs")
    return {
        "constraint_mhz": 1000.0 / float(fmax["period_ns"]),
        "fmax_mhz": float(fmax["fmax_mhz"]),
        "wns_ns": float(fmax["wns_ns"]),
        "logic_levels": int(levels.group(1)) if levels else None,
        "lut": as_int(lut),
        "lutram": as_int(used("LUT as Memory")),
        "ff": as_int(used("Slice Registers")),
        "bram": as_int(used("Block RAM Tile")),
        "dsp": as_int(used("DSPs")),
    }


def evaluate(args: argparse.Namespace, repo: Path, core: str, spec: dict, target_name: str,
             target: dict, variant: str, out_dir: Path) -> dict:
    tool = target["tool"]
    exe = args.gowin if tool == "gowin" else args.vivado
    run_dir = out_dir / target_name / core / variant
    run_dir.mkdir(parents=True, exist_ok=True)
    build_tcl = write_build_tcl(repo, core, spec, target, variant, run_dir, is_windows_tool(exe))
    run_tool(args, tool, run_dir, build_tcl)
    result = parse_gowin(run_dir, core) if tool == "gowin" else parse_vivado(run_dir)
    result.update({
        "core": core, "target": target_name, "tool": tool, "device": target["device"],
        "variant": variant, "date": datetime.datetime.now().isoformat(timespec="seconds"),
    })
    (run_dir / "summary.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


def best_runs(results: list[dict]) -> list[dict]:
    """One row per core and target: the variant with the highest Fmax, plus
    the Fmax of every variant that ran."""
    groups: dict[tuple[str, str], list[dict]] = {}
    for r in results:
        groups.setdefault((r["core"], r["target"]), []).append(r)
    rows = []
    for runs in groups.values():
        best = dict(max(runs, key=lambda r: r["fmax_mhz"]))
        best["variants"] = {r["variant"]: r["fmax_mhz"]
                            for r in sorted(runs, key=lambda r: r["variant"])}
        rows.append(best)
    return rows


def merge_summary(path: Path, new: list[dict]) -> list[dict]:
    rows = json.loads(path.read_text()) if path.exists() else []
    keys = {(r["core"], r["target"]) for r in new}
    rows = [r for r in rows if (r["core"], r["target"]) not in keys] + new
    rows.sort(key=lambda r: (r["target"], r["core"]))
    path.write_text(json.dumps(rows, indent=2) + "\n")
    return rows


def print_table(rows: list[dict]) -> None:
    headers = ["target", "core", "Fmax MHz", "variant", "range", "levels", "LUT", "LUTRAM", "FF",
               "BRAM", "DSP"]
    keys = ["target", "core", "fmax_mhz", "variant", "range", "logic_levels", "lut", "lutram", "ff",
            "bram", "dsp"]

    def cell(r: dict, k: str) -> str:
        if k == "range":
            fmax = list(r.get("variants", {}).values())
            return f"{min(fmax):.2f}-{max(fmax):.2f}" if len(fmax) > 1 else "-"
        v = r.get(k, "-")
        return f"{v:.2f}" if isinstance(v, float) else str(v)

    table = [[cell(r, k) for k in keys] for r in rows]
    widths = [max([len(h)] + [len(row[i]) for row in table]) for i, h in enumerate(headers)]
    print("  ".join(h.ljust(w) for h, w in zip(headers, widths)))
    print("  ".join("-" * w for w in widths))
    for row in table:
        print("  ".join(c.ljust(w) for c, w in zip(row, widths)))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--cores", default="all", help="comma-separated core names (default: all)")
    parser.add_argument("--targets", default="all", help="comma-separated targets (default: all)")
    parser.add_argument("--out-dir", default="build/fpga_eval")
    parser.add_argument("--variants", default="default",
                        help="implementation variants from targets.json: default (the first "
                             "of each target), all, or a comma-separated list of names")
    parser.add_argument("--jobs", type=int, default=2, help="parallel tool runs (default: 2)")
    parser.add_argument("--gowin", default=os.environ.get("GOWIN_SH", "gw_sh"),
                        help="Gowin gw_sh (or gw_sh.exe from WSL); default $GOWIN_SH or gw_sh")
    parser.add_argument("--vivado", default=os.environ.get("VIVADO", "vivado"),
                        help="Vivado (or vivado.bat from WSL); default $VIVADO or vivado")
    args = parser.parse_args()

    repo = Path(__file__).resolve().parent.parent
    out_dir = Path(args.out_dir).resolve()
    all_cores = json.loads((repo / CORES_JSON).read_text())
    all_targets = json.loads((repo / TARGETS_JSON).read_text())

    cores = list(all_cores) if args.cores == "all" else split_list(args.cores)
    targets = list(all_targets) if args.targets == "all" else split_list(args.targets)
    for name, known, source in [("core", all_cores, CORES_JSON), ("target", all_targets, TARGETS_JSON)]:
        unknown = sorted(set(cores if name == "core" else targets) - set(known))
        if unknown:
            raise SystemExit(f"unknown {name}(s): {', '.join(unknown)}; see {source}")

    runs = []
    for t in targets:
        variants = list(target_variants(all_targets[t]))
        if args.variants == "default":
            selected = variants[:1]
        elif args.variants == "all":
            selected = variants
        else:
            selected = [v for v in split_list(args.variants) if v in variants]
            if not selected:
                raise SystemExit(f"target {t} has none of the variants {args.variants}; "
                                 f"it has {', '.join(variants)}")
        runs += [(c, t, v) for c in cores for v in selected]

    results, failures = [], 0
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        futures = {pool.submit(evaluate, args, repo, c, all_cores[c], t, all_targets[t], v, out_dir):
                   (c, t, v) for c, t, v in runs}
        for fut in concurrent.futures.as_completed(futures):
            core, target, variant = futures[fut]
            try:
                r = fut.result()
                results.append(r)
                print(f"DONE {target} {core} {variant}: {r['fmax_mhz']:.2f} MHz, {r['lut']} LUT",
                      flush=True)
            except (RuntimeError, OSError, KeyError, ValueError) as exc:
                failures += 1
                print(f"FAIL {target} {core} {variant}: {exc}", file=sys.stderr, flush=True)

    out_dir.mkdir(parents=True, exist_ok=True)
    rows = merge_summary(out_dir / "summary.json", best_runs(results))
    print()
    print_table(rows)
    print(f"\nWrote {out_dir / 'summary.json'}")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
