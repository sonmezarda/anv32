// FPGA top for boards whose pins match these ports (the Tang Nano 9K build):
// anv32_soc with the same parameters and without external RAM, so the AXI
// ports of anv32_soc stay inside. See anv32_soc for what each parameter does.
module anv32_soc_top #(
    parameter int unsigned CORE_TYPE   = 2,           // 0 = i1, 1 = im1, 2 = im2
    parameter bit          MUL_PIPE    = 1'b0,        // im2: two-cycle registered multiply
    parameter int unsigned BRAM_ADDR_W = 13,
    parameter int unsigned POR_CYCLES  = 8,
    parameter              INIT_FILE   = "src/prog",
    parameter int unsigned CLK_FREQ    = 27_000_000,  // Hz, for UART/I2C timing
    parameter int unsigned MTIME_FREQ  = 1_000_000,   // Hz, CLINT mtime rate; must divide CLK_FREQ

    // Peripherals
    parameter bit HAS_CLINT   = 1'b1,
    parameter bit HAS_GPIO    = 1'b1,
    parameter bit HAS_NN      = 1'b0,
    parameter bit HAS_SYSCTRL = 1'b1,
    parameter bit HAS_UART    = 1'b1,
    parameter bit HAS_I2C     = 1'b1,

    // UART bootloader in the top BOOT_SIZE bytes of the BRAM
    parameter bit          HAS_BOOTLOADER = 1'b1,
    parameter int unsigned BOOT_SIZE      = 1024,
    parameter int unsigned BOOT_BAUD      = 115_200
)(
    input  logic       clk_i,
    input  logic       rst_n_i,
    input  logic       gpio_irq_i,
    input  logic       uart_rx_i,
    inout  logic       i2c_sda_io,
    inout  logic       i2c_scl_io,
    output logic       uart_tx_o,
    output logic [3:0] debug_leds
);
    anv32_soc #(
        .CORE_TYPE     (CORE_TYPE),
        .MUL_PIPE      (MUL_PIPE),
        .BRAM_ADDR_W   (BRAM_ADDR_W),
        .POR_CYCLES    (POR_CYCLES),
        .INIT_FILE     (INIT_FILE),
        .CLK_FREQ      (CLK_FREQ),
        .MTIME_FREQ    (MTIME_FREQ),
        .HAS_CLINT     (HAS_CLINT),
        .HAS_GPIO      (HAS_GPIO),
        .HAS_NN        (HAS_NN),
        .HAS_SYSCTRL   (HAS_SYSCTRL),
        .HAS_UART      (HAS_UART),
        .HAS_I2C       (HAS_I2C),
        .HAS_BOOTLOADER(HAS_BOOTLOADER),
        .BOOT_SIZE     (BOOT_SIZE),
        .BOOT_BAUD     (BOOT_BAUD),
        .HAS_EXT_RAM   (1'b0)
    ) soc (
        .clk_i            (clk_i),
        .rst_n_i          (rst_n_i),
        .gpio_irq_i       (gpio_irq_i),
        .uart_rx_i        (uart_rx_i),
        .i2c_sda_io       (i2c_sda_io),
        .i2c_scl_io       (i2c_scl_io),
        .uart_tx_o        (uart_tx_o),
        .debug_leds       (debug_leds),
        .ext_addr_offset_i(32'b0),
        .m_axi_i_arid     (),
        .m_axi_i_araddr   (),
        .m_axi_i_arlen    (),
        .m_axi_i_arsize   (),
        .m_axi_i_arburst  (),
        .m_axi_i_arlock   (),
        .m_axi_i_arcache  (),
        .m_axi_i_arprot   (),
        .m_axi_i_arqos    (),
        .m_axi_i_arvalid  (),
        .m_axi_i_arready  (1'b0),
        .m_axi_i_rid      (6'd0),
        .m_axi_i_rdata    (64'd0),
        .m_axi_i_rresp    (2'd0),
        .m_axi_i_rlast    (1'b0),
        .m_axi_i_rvalid   (1'b0),
        .m_axi_i_rready   (),
        .m_axi_d_arid     (),
        .m_axi_d_araddr   (),
        .m_axi_d_arlen    (),
        .m_axi_d_arsize   (),
        .m_axi_d_arburst  (),
        .m_axi_d_arlock   (),
        .m_axi_d_arcache  (),
        .m_axi_d_arprot   (),
        .m_axi_d_arqos    (),
        .m_axi_d_arvalid  (),
        .m_axi_d_arready  (1'b0),
        .m_axi_d_rid      (6'd0),
        .m_axi_d_rdata    (64'd0),
        .m_axi_d_rresp    (2'd0),
        .m_axi_d_rlast    (1'b0),
        .m_axi_d_rvalid   (1'b0),
        .m_axi_d_rready   (),
        .m_axi_d_awid     (),
        .m_axi_d_awaddr   (),
        .m_axi_d_awlen    (),
        .m_axi_d_awsize   (),
        .m_axi_d_awburst  (),
        .m_axi_d_awlock   (),
        .m_axi_d_awcache  (),
        .m_axi_d_awprot   (),
        .m_axi_d_awqos    (),
        .m_axi_d_awvalid  (),
        .m_axi_d_awready  (1'b0),
        .m_axi_d_wid      (),
        .m_axi_d_wdata    (),
        .m_axi_d_wstrb    (),
        .m_axi_d_wlast    (),
        .m_axi_d_wvalid   (),
        .m_axi_d_wready   (1'b0),
        .m_axi_d_bid      (6'd0),
        .m_axi_d_bresp    (2'd0),
        .m_axi_d_bvalid   (1'b0),
        .m_axi_d_bready   ()
    );
endmodule
