#ifndef ANV32_GPIO_H
#define ANV32_GPIO_H

#include "anv32_mmio.h"

#define ANV32_GPIO_DATA_OFFSET          0x000u
#define ANV32_GPIO_DIR_OFFSET           0x004u
#define ANV32_GPIO_OUT_SET_OFFSET       0x008u
#define ANV32_GPIO_OUT_CLR_OFFSET       0x00Cu
#define ANV32_GPIO_IRQ_PENDING_OFFSET   0x010u
#define ANV32_GPIO_IRQ_ENABLE_OFFSET    0x014u

#define ANV32_GPIO_DATA(base)           ANV32_REG32((base) + ANV32_GPIO_DATA_OFFSET)
#define ANV32_GPIO_DIR(base)            ANV32_REG32((base) + ANV32_GPIO_DIR_OFFSET)
#define ANV32_GPIO_OUT_SET(base)        ANV32_REG32((base) + ANV32_GPIO_OUT_SET_OFFSET)
#define ANV32_GPIO_OUT_CLR(base)        ANV32_REG32((base) + ANV32_GPIO_OUT_CLR_OFFSET)
#define ANV32_GPIO_IRQ_PENDING(base)    ANV32_REG32((base) + ANV32_GPIO_IRQ_PENDING_OFFSET)
#define ANV32_GPIO_IRQ_ENABLE(base)     ANV32_REG32((base) + ANV32_GPIO_IRQ_ENABLE_OFFSET)

#define ANV32_GPIO0_DATA                ANV32_GPIO_DATA(ANV32_GPIO0_BASE)
#define ANV32_GPIO0_DIR                 ANV32_GPIO_DIR(ANV32_GPIO0_BASE)
#define ANV32_GPIO0_OUT_SET             ANV32_GPIO_OUT_SET(ANV32_GPIO0_BASE)
#define ANV32_GPIO0_OUT_CLR             ANV32_GPIO_OUT_CLR(ANV32_GPIO0_BASE)
#define ANV32_GPIO0_IRQ_PENDING         ANV32_GPIO_IRQ_PENDING(ANV32_GPIO0_BASE)
#define ANV32_GPIO0_IRQ_ENABLE          ANV32_GPIO_IRQ_ENABLE(ANV32_GPIO0_BASE)

#endif
