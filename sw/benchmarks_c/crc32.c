static u32 crc32_slow(void)
{
    u32 crc = 0xffffffffu;

    for (int i = 0; i < 64; i++) {
        crc ^= (u32)input_data[i];
        for (int bit = 0; bit < 8; bit++) {
            u32 mask = 0u - (crc & 1u);
            crc = (crc >> 1) ^ (0xedb88320u & mask);
        }
    }

    return ~crc;
}

